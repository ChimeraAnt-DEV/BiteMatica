// --- out-of-line implementations (header-only so the host tests and the mod share one copy) -----

inline std::unordered_map<std::string, Color> &BlockColors::mutableTable() {
  // The default table, overlaid by whatever `loadJson`/`loadFile` merged in. A function-local
  // static so the table is built once, on first use.
  static std::unordered_map<std::string, Color> table = defaultTable();
  return table;
}

inline std::vector<std::string> &unknownColorRegistry() {
  static std::vector<std::string> seen;
  return seen;
}

inline std::unordered_map<std::string, bool> &unknownColorPresent() {
  static std::unordered_map<std::string, bool> present;
  return present;
}

inline void BlockColors::recordUnknown(const std::string &key) {
  // A small cap so a pathological schematic cannot grow this without bound; the status line only
  // needs a count and a few examples.
  auto &seen = unknownColorRegistry();
  auto &present = unknownColorPresent();
  if (seen.size() >= 256) return;
  if (present.count(key) != 0) return;
  present[key] = true;
  seen.push_back(key);
}

inline std::vector<std::string> BlockColors::unknownBlocks() { return unknownColorRegistry(); }

inline void BlockColors::clearUnknowns() {
  unknownColorRegistry().clear();
  unknownColorPresent().clear();
}

inline int BlockColors::loadJson(const std::string &json) {
  // A deliberately tiny scanner for a flat object: `{ "id": [r,g,b(,a)] | "#rrggbb", ... }`. It does
  // not need to be a general JSON parser; it must be robust to a malformed entry (skip it) and to
  // comments/whitespace. Returns the number of colours merged.
  auto skipWs = [](const std::string &s, size_t &i) {
    while (i < s.size() && std::isspace(static_cast<unsigned char>(s[i]))) ++i;
  };
  auto &table = mutableTable();
  int merged = 0;
  size_t i = 0;
  skipWs(json, i);
  if (i >= json.size() || json[i] != '{') return 0;
  ++i;
  while (i < json.size()) {
    skipWs(json, i);
    if (i < json.size() && json[i] == '}') break;
    if (i >= json.size() || json[i] != '"') break;
    // key
    ++i;
    std::string key;
    while (i < json.size() && json[i] != '"') key.push_back(json[i++]);
    if (i < json.size()) ++i; // closing quote
    skipWs(json, i);
    if (i >= json.size() || json[i] != ':') break;
    ++i;
    skipWs(json, i);
    Color color;
    bool ok = false;
    if (i < json.size() && json[i] == '"') {
      ++i;
      std::string hex;
      while (i < json.size() && json[i] != '"') hex.push_back(json[i++]);
      if (i < json.size()) ++i;
      if (!hex.empty() && hex[0] == '#') hex = hex.substr(1);
      if (hex.size() >= 6) {
        const int r = static_cast<int>(std::strtol(hex.substr(0, 2).c_str(), nullptr, 16));
        const int g = static_cast<int>(std::strtol(hex.substr(2, 2).c_str(), nullptr, 16));
        const int b = static_cast<int>(std::strtol(hex.substr(4, 2).c_str(), nullptr, 16));
        const int a = hex.size() >= 8
                          ? static_cast<int>(std::strtol(hex.substr(6, 2).c_str(), nullptr, 16))
                          : 255;
        color = Color::rgb(r, g, b, a);
        ok = true;
      }
    } else if (i < json.size() && json[i] == '[') {
      ++i;
      int parts[4] = {0, 0, 0, 255};
      int count = 0;
      while (i < json.size() && json[i] != ']' && count < 4) {
        skipWs(json, i);
        if (json[i] == ']') break;
        const long value = std::strtol(json.c_str() + i, nullptr, 10);
        parts[count++] = static_cast<int>(value);
        while (i < json.size() && json[i] != ',' && json[i] != ']') ++i;
        if (i < json.size() && json[i] == ',') ++i;
      }
      if (i < json.size() && json[i] == ']') ++i;
      if (count >= 3) {
        color = Color::rgb(parts[0], parts[1], parts[2], count >= 4 ? parts[3] : 255);
        ok = true;
      }
    }
    if (ok && !key.empty()) {
      table[normalize(key)] = color;
      ++merged;
    }
    skipWs(json, i);
    if (i < json.size() && json[i] == ',') {
      ++i;
      continue;
    }
    if (i < json.size() && json[i] == '}') break;
    break; // malformed tail: stop, keep what merged
  }
  return merged;
}

inline int BlockColors::loadFile(const std::string &path) {
  std::ifstream in(path);
  if (!in) return 0;
  std::string text((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
  return loadJson(text);
}

